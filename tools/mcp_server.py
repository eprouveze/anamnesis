def default_host_origin_protection(allowed_hosts: list[str] | None):
    """DNS-rebinding guard mode for fastmcp (accepted: True | False | "auto").

    fastmcp's own default is False (no guard). We use strict validation of every request's
    Host/Origin when an explicit allowlist is configured or unauthenticated loopback is on
    (the case a rebinding page can actually exploit), and "auto" otherwise.
    """
    return True if (allowed_hosts or _flag("ANAMNESIS_ALLOW_LOCALHOST_NOAUTH")) else "auto"


def build_http_app(*, allowed_hosts: list[str] | None = None, host_origin_protection=None,
                   oauth_storage=None):
    """ASGI app: PreAuth -> concurrency cap -> fastmcp app (bearer auth + MCP at /mcp + /health)."""
    global _TRANSPORT
    _TRANSPORT = "http"
    mcp.auth = build_auth(oauth_storage)
    if allowed_hosts is None:
        allowed_hosts = _csv_env("ANAMNESIS_ALLOWED_HOSTS") or None
    if host_origin_protection is None:
        host_origin_protection = default_host_origin_protection(allowed_hosts)
    app = mcp.http_app(path="/mcp", transport="streamable-http", stateless_http=True,
                       allowed_hosts=allowed_hosts, host_origin_protection=host_origin_protection)
    app = McpConcurrencyLimitMiddleware(app, max_concurrent=int(os.environ.get("ANAMNESIS_MCP_MAX_CONCURRENT", "20")))
    return PreAuthMiddleware(app, "/mcp")


def _client_cli(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(prog="mcp_server.py", description="Manage Anamnesis client tokens")
    sub = ap.add_subparsers(dest="cmd", required=True)
    a = sub.add_parser("add-client", help="create a client; prints its token ONCE")
    a.add_argument("name")
    a.add_argument("--read-only", action="store_true", help="no write scope (store_* refused)")
    sub.add_parser("list-clients", help="list clients (names, scopes; never tokens)")
    r = sub.add_parser("revoke-client", help="delete a client")
    r.add_argument("name")
    args = ap.parse_args(argv)
    if args.cmd == "add-client":
        try:
            token = add_client(args.name, read_only=args.read_only)
        except ValueError as e:
            print(f"error: {e}", file=sys.stderr)
            return 1
        print(f"Client '{args.name}' created ({'read' if args.read_only else 'read, write'}) in {CLIENTS_PATH}.",
              file=sys.stderr)
        print("The token below is shown once; only its SHA-256 is stored. Send it as "
              "'Authorization: Bearer <token>'.", file=sys.stderr)
        print(token)
        return 0
    if args.cmd == "list-clients":
        for c in load_clients():
            print(f"{c['name']}\t{','.join(c['scopes'])}")
        return 0
    if revoke_client(args.name):
        print(f"Client '{args.name}' revoked.", file=sys.stderr)
        return 0
    print(f"error: no client named '{args.name}'", file=sys.stderr)
    return 1


def _serve_cli(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description="Anamnesis MCP server")
    ap.add_argument("--transport", default="streamable-http", choices=["stdio", "streamable-http"])
    ap.add_argument("--host", default=os.environ.get("ANAMNESIS_HOST", "127.0.0.1"))
    ap.add_argument("--port", type=int, default=PORT)
    args = ap.parse_args(argv)
    configure_logging()

    if DB_PATH.exists() and ROLE != "replica":
        try:
            conn = get_db()
            try:
                validity.ensure_validity_schema(conn)  # additive, idempotent
            finally:
                conn.close()
        except sqlite3.Error as e:
            app_logger.warning("schema check skipped: %s", e)

    app_logger.info("Starting Anamnesis MCP server (role=%s, transport=%s)", ROLE, args.transport)
    if args.transport == "stdio":
        global _TRANSPORT
        _TRANSPORT = "stdio"
        mcp.run(transport="stdio")
        return 0

    if _flag("ANAMNESIS_ALLOW_QUERY_TOKEN"):
        app_logger.warning("SECURITY: ANAMNESIS_ALLOW_QUERY_TOKEN is ON. Tokens in URLs leak into client "
                           "configs, proxy logs and transcripts. Prefer the Authorization header.")
    if _flag("ANAMNESIS_ALLOW_LOCALHOST_NOAUTH"):
        app_logger.warning("SECURITY: ANAMNESIS_ALLOW_LOCALHOST_NOAUTH is ON: direct loopback requests need "
                           "no token. Never enable this behind a reverse proxy.")
    if not load_clients() and oauth_provider_name() is None and not _flag("ANAMNESIS_ALLOW_LOCALHOST_NOAUTH"):
        app_logger.warning("No clients configured: every request will be rejected. "
                           "Run: python tools/mcp_server.py add-client <name>")
    app = build_http_app()
    import uvicorn
    # access_log off: request lines would record URLs (and any ?token=) of rejected requests.
    uvicorn.run(app, host=args.host, port=args.port, access_log=False, log_level="info")
    return 0


def main(argv: list[str] | None = None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    if argv and argv[0] in ("add-client", "list-clients", "revoke-client"):
        return _client_cli(argv)
    if argv and argv[0] == "serve":
        argv = argv[1:]
    return _serve_cli(argv)


if __name__ == "__main__":
    sys.exit(main())
