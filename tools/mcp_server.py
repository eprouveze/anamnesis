#!/usr/bin/env python3
"""Anamnesis MCP server: memory access for agents over MCP (stdio or HTTP).

Wraps the memory.db built by tools/index.py (FTS5 + embedding rerank) and the
git-tracked memory files under ANAMNESIS_DATA_DIR as MCP tools.

Run:
  python tools/mcp_server.py                         # HTTP on 127.0.0.1:7777/mcp
  python tools/mcp_server.py --transport stdio       # local stdio (trusted)
  python tools/mcp_server.py add-client laptop       # create a read/write client token
  python tools/mcp_server.py add-client viewer --read-only
  python tools/mcp_server.py list-clients
  python tools/mcp_server.py revoke-client laptop

Authentication (HTTP transport)
-------------------------------
* Default: `Authorization: Bearer <token>`. Tokens are generated by `add-client`,
  shown once, and only their SHA-256 is stored in $ANAMNESIS_HOME/clients.json:

    {"clients": [{"name": "laptop", "token_sha256": "<64 hex>",
                  "scopes": ["read", "write"], "created_at": "2026-01-01T00:00:00Z"}]}

  Hashes are compared with hmac.compare_digest. A client without the "write" scope
  cannot call store_memory / store_decision.
* A token in the URL (`?token=`) leaks into configs, proxy logs and transcripts, so it
  is rejected unless ANAMNESIS_ALLOW_QUERY_TOKEN=1 (off by default; logged loudly).
* stdio is trusted: the client is the local process that spawned the server.
* Unauthenticated loopback HTTP is off unless ANAMNESIS_ALLOW_LOCALHOST_NOAUTH=1
  (read-only unless ANAMNESIS_LOCALHOST_WRITE=1). Do not enable it behind a proxy.
* Optional OAuth for GUI connectors that cannot send headers (see build_oauth_provider):
  ANAMNESIS_OAUTH_PROVIDER=google|github plus a server-side allowlist. Static bearer
  tokens keep working alongside it for headless clients (fastmcp MultiAuth).

Environment
-----------
  ANAMNESIS_HOME                   state dir (default ~/.anamnesis): memory.db, clients.json, logs/
  ANAMNESIS_DATA_DIR               git-tracked memory (default <repo>/data)
  ANAMNESIS_DB                     path to memory.db (default $ANAMNESIS_HOME/memory.db)
  ANAMNESIS_CLIENTS                clients file (default $ANAMNESIS_HOME/clients.json)
  ANAMNESIS_LOG_DIR                log dir (default $ANAMNESIS_HOME/logs)
  ANAMNESIS_ROLE                   primary (default) | replica (read-only: store_* refused)
  ANAMNESIS_DEFAULT_PROJECT        project label for new memories (default "default")
  ANAMNESIS_FILE_ROOTS             read_file/list_files roots: name=/abs/dir,name2=/abs/dir2
                                   (default: data=$ANAMNESIS_DATA_DIR)
  ANAMNESIS_HOST / ANAMNESIS_PORT  HTTP bind (default 127.0.0.1 / 7777)
  ANAMNESIS_ALLOWED_HOSTS          extra Host header values to accept (comma-separated)
  ANAMNESIS_MCP_MAX_CONCURRENT     cap on concurrent /mcp requests (default 20)
  ANAMNESIS_INDEX_STALE_H          hours before the index is reported stale (default 30)
  ANAMNESIS_GIT_AUTOCOMMIT         1 = commit memory files written by store_* (default 0)
  ANAMNESIS_AUDIT_LOG_QUERIES      1 = include query text in audit logs (default 0)
  ANAMNESIS_ALLOW_QUERY_TOKEN, ANAMNESIS_ALLOW_LOCALHOST_NOAUTH, ANAMNESIS_LOCALHOST_WRITE
  ANAMNESIS_OAUTH_PROVIDER, ANAMNESIS_OAUTH_CLIENT_ID, ANAMNESIS_OAUTH_CLIENT_SECRET,
  ANAMNESIS_OAUTH_BASE_URL, ANAMNESIS_OAUTH_ALLOWED_EMAILS (google),
  ANAMNESIS_OAUTH_ALLOWED_LOGINS (github; entries are logins or stable "id:12345"),
  ANAMNESIS_OAUTH_SCOPES (default "read"; add write explicitly), ANAMNESIS_OAUTH_JWT_KEY
Secrets (e.g. GEMINI_API_KEY) come from the process environment only.
"""
