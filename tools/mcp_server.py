def _parse_raw_decisions(path: Path) -> list[str]:
    """Split decisions/log.md into entries at '### YYYY-MM-DD' headings."""
    if not path.exists():
        return []
    parts = re.split(r"(?=^### \d{4}-\d{2}-\d{2})", path.read_text(encoding="utf-8"), flags=re.MULTILINE)
    return [p.strip() for p in parts if p.strip().startswith("### ")]


def _match_full_entry(title_snippet: str, raw_entries: list[str]) -> str | None:
    """Find the full log entry for a chunk titled like '2026-03-17 - Some title'."""
    m = _DATE_RE.search(title_snippet)
    if not m:
        return None
    date_str = m.group()
    words = re.split(r"[—-]", title_snippet.lower())[-1].strip().split()[:3]
    for entry in raw_entries:
        if date_str in entry and any(w in entry.lower() for w in words):
            return entry
    return next((e for e in raw_entries if date_str in e), None)


def parse_decision_fields(text: str) -> dict[str, str]:
    """Parse a decision entry into context / decision / alternatives / rationale."""
    fields = {"context": "", "decision": "", "alternatives": "", "rationale": ""}
    if not text:
        return fields
    pattern = re.compile(
        r"(?:^|\n)\s*\*\*(?P<field>Context|Decision|Alternatives(?:\s+considered|\s+rejected)?|Rationale|Why|"
        r"Topic IDs|Applies to|Evidence|What)\s*:?\*\*:?\s*", re.IGNORECASE)
    matches = list(pattern.finditer(text))
    for i, m in enumerate(matches):
        name = m.group("field").strip().lower()
        end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
        val = re.sub(r"\n+---\s*$", "", text[m.end():end].strip()).strip()
        if "context" in name:
            fields["context"] = val
        elif "decision" in name:
            fields["decision"] = val
        elif "alternative" in name:
            fields["alternatives"] = val
        elif "rationale" in name or name == "why":
            fields["rationale"] = val
    return fields


def _with_decision_fields(item: dict, content: str) -> dict:
    f = parse_decision_fields(content)
    item.update(context=f["context"], decision=f["decision"],
                alternatives=f["alternatives"], rationale=f["rationale"])
    return item


