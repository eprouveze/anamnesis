@mcp.tool
def get_decisions(project: str | None = None, since: str | None = None, limit: int = 20,
                  query: str | None = None) -> list[str]:
    """Retrieve decisions from decisions/log.md.

    Filter by project and date (legacy mode), or search by topic with FTS + embedding rerank
    (when `query` is given). Returns decision entries as strings, then ONE trailing string
    starting "[freshness]". Query mode searches the index, so a stale index means recent
    decisions can be missing: the trailer then carries the index warning, relay it. Legacy
    mode reads the log live; the trailer gives its mtime.
    """
    start = time.time()
    path = decisions_log_path()
    if not path.exists():
        return []
    idx = index_freshness()
    raw_entries = _parse_raw_decisions(path)
    limit = max(1, min(limit, 100))

    if query and DB_PATH.exists():
        conn = get_db()
        try:
            rows, _ = recall_core.search_chunks(conn, query, limit=limit * 3 if project else limit,
                                                store_types=["decision"], embed=_embedder())
        finally:
            conn.close()
        if project:
            rows = [r for r in rows if project.lower() in (r.get("content") or "").lower()]
        results = [_match_full_entry(r["title"], raw_entries) or r["content"] for r in rows[:limit]]
        note = f"[freshness] searched the {_freshness_note(idx)}"
        if idx.get("index_warning"):
            note += f". WARNING: {idx['index_warning']}"
        audit_log("get_decisions", f"query={query} project={project}", len(results), (time.time() - start) * 1000)
        return results + [note]

    results = []
    for entry in raw_entries:
        if project and project.lower() not in entry.lower():
            continue
        if since:
            m = _DATE_RE.search(entry)
            if m and m.group() < since:
                continue
        results.append(entry)
    results = results[-limit:]
    try:
        mtime = _fmt_utc(datetime.fromtimestamp(path.stat().st_mtime, timezone.utc))
    except OSError:
        mtime = "unknown"
    audit_log("get_decisions", f"project={project} since={since}", len(results), (time.time() - start) * 1000)
    return results + [f"[freshness] read live from decisions/log.md (modified {mtime})"]


@mcp.tool
def health() -> dict:
    """Server status: uptime, index stats, freshness and auth telemetry (counters only).

    `index_updated_at` / `index_age_h` / `index_stale` say when the batch indexer last
    succeeded, the real currency of every answer. `data_fresh_as_of` (newest indexed_at) is
    NOT an indexer liveness signal: store_memory/store_decision keep it fresh while the
    indexer is down.
    """
    chunks, embedded, meta, data_fresh_as_of = 0, 0, {}, None
    if DB_PATH.exists():
        conn = get_db()
        try:
            chunks = conn.execute("SELECT COUNT(*) FROM chunks").fetchone()[0]
            embedded = conn.execute("SELECT COUNT(*) FROM chunks WHERE embedding IS NOT NULL").fetchone()[0]
            data_fresh_as_of = conn.execute("SELECT MAX(indexed_at) FROM chunks").fetchone()[0]
            meta = {r["key"]: r["value"] for r in conn.execute("SELECT * FROM index_meta").fetchall()}
        except sqlite3.Error:
            pass
        finally:
            conn.close()
    return {
        "status": "ok", "role": ROLE, "uptime_s": int(time.time() - START_TIME),
        "data_fresh_as_of": data_fresh_as_of, "last_updated": meta.get("last_updated"),
        **_compose_freshness(meta.get("last_updated"), DB_PATH.stat().st_mtime if DB_PATH.exists() else None),
        "index_stale_after_h": INDEX_STALE_AFTER_H, "last_built": meta.get("last_built"),
        "chunks_count": chunks, "embedded_count": embedded,
        "embedding_model": meta.get("embedding_model", "unknown"),
        "db_size_mb": round(DB_PATH.stat().st_size / 1024 / 1024, 1) if DB_PATH.exists() else 0,
        "client_count": len(load_clients()),
        "auth_failure_count": _auth_stats["failures"],
        "auth_failures_by_transport": dict(_auth_stats["by_transport"]),
        "auth_failures_by_reason": dict(_auth_stats["by_reason"]),
        "last_auth_failure_at": _auth_stats["last_failure_at"],
    }


# ---------------------------------------------------------------------------
# File access tools (confined to configured roots)
# ---------------------------------------------------------------------------
# Allowlist of readable text extensions (ANAMNESIS_FILE_EXTENSIONS overrides, comma-separated).
# Everything else, and every dotfile / dot-directory, is refused. All name comparisons are
# casefolded so `.ENV` or `NODE_MODULES` behave like their lower-case forms on case-insensitive
# filesystems.
_DEFAULT_EXTENSIONS = (".md", ".json", ".jsonl", ".txt", ".yaml", ".yml", ".csv", ".toml")
_BLOCKED_DIRS = {"node_modules", "__pycache__", "venv", "dist", "kube"}
_BLOCKED_NAMES = {"clients.json", ".netrc", ".npmrc", ".pypirc", ".git-credentials", ".pgpass",
                  "id_rsa", "id_dsa", "id_ecdsa", "id_ed25519", "credentials", "credentials.json",
                  "secrets.json"}
_BLOCKED_SUFFIXES = (".kdbx", ".sql", ".bak", ".dump", ".key", ".pem", ".p12", ".pfx", ".jks",
                     ".keystore", ".env", ".db", ".sqlite", ".sqlite3", ".db-wal", ".db-shm")
_MAX_READ_BYTES = 512_000
_MAX_LIST_ENTRIES = 500


def readable_extensions() -> tuple[str, ...]:
    custom = [e.lower() if e.startswith(".") else "." + e.lower() for e in _csv_env("ANAMNESIS_FILE_EXTENSIONS")]
    return tuple(custom) or _DEFAULT_EXTENSIONS


def file_roots() -> dict[str, Path]:
    """Configured roots: ANAMNESIS_FILE_ROOTS='name=/abs/dir,...', default {'data': DATA_DIR}."""
    spec = os.environ.get("ANAMNESIS_FILE_ROOTS", "").strip()
    if not spec:
        return {"data": DATA_DIR}
    roots: dict[str, Path] = {}
    for item in spec.split(","):
        name, sep, path = item.partition("=")
        name, path = name.strip(), path.strip()
        if sep and _NAME_RE.match(name) and path:
            roots[name] = Path(path)
    return roots


def _same_file(a: Path, b: Path) -> bool:
    try:
        return os.path.samefile(a, b)
    except OSError:
        return a == b


def _is_sensitive(target: Path) -> bool:
    """Files the server itself depends on (credentials registry, the database)."""
    guarded = [CLIENTS_PATH, DB_PATH, DB_PATH.with_name(DB_PATH.name + "-wal"),
               DB_PATH.with_name(DB_PATH.name + "-shm")]
    return any(_same_file(target, g) for g in guarded if g.exists())


def _name_blocked(name: str, is_dir: bool) -> bool:
    n = name.casefold()
    if n.startswith("."):
        return True  # every dotfile / dot-directory (.env, .git, .ssh, .docker, .kube, ...)
    if n in _BLOCKED_NAMES:
        return True
    if is_dir:
        return n in _BLOCKED_DIRS
    return n.endswith(_BLOCKED_SUFFIXES) or not n.endswith(readable_extensions())


def resolve_confined(root: str | None, rel_path: str) -> tuple[Path | None, Path | None, str | None]:
    """Resolve rel_path inside a configured root. Returns (target, base, error).

    The target is fully resolved (symlinks followed) and must stay inside the resolved root,
    so `..`, absolute paths and symlinks pointing outside are all rejected, as is any path
    component that is a dotfile or blocked directory.
    """
    roots = file_roots()
    if not roots:
        return None, None, "No file roots configured"
    name = root or next(iter(roots))
    if name not in roots:
        return None, None, f"Unknown root '{root}'. Available: {sorted(roots)}"
    if "\x00" in rel_path:
        return None, None, "Invalid path"
    try:
        base = roots[name].resolve(strict=True)
    except (OSError, RuntimeError):
        return None, None, f"Root '{name}' is not available"
    try:
        target = (base / rel_path.lstrip("/\\")).resolve()
        rel_parts = target.relative_to(base).parts
    except (ValueError, OSError, RuntimeError):
        return None, None, "Path is outside the allowed root"
    for i, part in enumerate(rel_parts):
        last = i == len(rel_parts) - 1
        # Intermediate components are directories; the last one is judged after is_dir() below.
        if part.startswith(".") or (not last and _name_blocked(part, True)):
            return None, None, "Access to this path is not allowed"
    try:
        if _is_sensitive(target):
            return None, None, "Access to this file is not allowed"
        if rel_parts and _name_blocked(rel_parts[-1], target.is_dir()):
            return None, None, "Access to this file type is not allowed"
    except (OSError, RuntimeError):
        return None, None, "Path cannot be accessed"
    return target, base, None


def _entry_ok(f: Path, base: Path) -> bool:
    """Listing filter: same rules as reads, plus symlinks must stay inside the root."""
    try:
        if _name_blocked(f.name, f.is_dir()):
            return False
        r = f.resolve()
        r.relative_to(base)
        return not _is_sensitive(r) and (r == base or not _name_blocked(r.name, r.is_dir()))
    except (ValueError, OSError, RuntimeError):
        return False


@mcp.tool
def read_file(path: str, root: str | None = None) -> dict:
    """Read a text file (or list a directory) from a configured file root.

    Args:
        path: relative path inside the root (e.g. 'decisions/log.md').
        root: root name (see ANAMNESIS_FILE_ROOTS); defaults to the first configured root.

    Paths are confined to the root: `..`, absolute paths and symlinks leaving it are refused.
    Only text extensions (.md .json .jsonl .txt .yaml .yml .csv .toml by default) are readable;
    dotfiles, credentials, keys, dumps and the server's own database/clients file are blocked.
    """
    start = time.time()
    target, base, err = resolve_confined(root, path)
    if err:
        return {"error": err, "path": path, "root": root}
    try:
        if not target.exists():
            return {"error": "File not found", "path": path, "root": root}
        if target.is_dir():
            entries = [{"name": f.name, "type": "dir" if f.is_dir() else "file",
                        "size": f.stat().st_size if f.is_file() else None}
                       for f in sorted(itertools.islice(target.iterdir(), 5000))
                       if _entry_ok(f, base)][:_MAX_LIST_ENTRIES]
            audit_log("read_file", f"ls:{root}:{path}", len(entries), (time.time() - start) * 1000)
            return {"path": path, "root": root, "type": "directory", "entries": entries}
        if not target.is_file():
            return {"error": "Not a regular file", "path": path}
        size = target.stat().st_size
        if size > _MAX_READ_BYTES:
            return {"error": "File too large", "path": path, "size_bytes": size, "limit": _MAX_READ_BYTES}
        content = target.read_text(encoding="utf-8", errors="replace")
    except (OSError, RuntimeError):
        return {"error": "Path cannot be accessed", "path": path, "root": root}
    audit_log("read_file", f"{root}:{path}", len(content), (time.time() - start) * 1000)
    return {"path": path, "root": root, "type": "file", "size_bytes": size, "content": content}


@mcp.tool
def list_files(directory: str, root: str | None = None, pattern: str | None = None) -> dict:
    """List readable files in a directory of a configured file root.

    Args:
        directory: relative directory (e.g. 'memory', '.').
        root: root name (see ANAMNESIS_FILE_ROOTS); defaults to the first configured root.
        pattern: optional glob to filter (e.g. '*.md', '**/*.json'). Matches that resolve
                 outside the root, or that read_file would refuse, are dropped.
    """
    start = time.time()
    target, base, err = resolve_confined(root, directory)
    if err:
        return {"error": err}
    entries = []
    try:
        if not target.is_dir():
            return {"error": "Directory not found", "path": directory, "root": root}
        files = sorted(itertools.islice(target.glob(pattern) if pattern else target.iterdir(), 5000))
        for f in files:
            if len(entries) >= _MAX_LIST_ENTRIES:
                break
            if not _entry_ok(f, base):
                continue
            rel = f.resolve().relative_to(base)
            if any(part.startswith(".") or part.casefold() in _BLOCKED_DIRS for part in rel.parts):
                continue
            entries.append({"path": str(rel), "name": f.name, "type": "dir" if f.is_dir() else "file",
                            "size": f.stat().st_size if f.is_file() else None})
    except (NotImplementedError, ValueError):
        return {"error": "Invalid glob pattern", "pattern": pattern}
    except (OSError, RuntimeError):
        return {"error": "Path cannot be accessed", "path": directory, "root": root}
    audit_log("list_files", f"{root}:{directory} pattern={pattern}", len(entries), (time.time() - start) * 1000)
    return {"directory": directory, "root": root, "count": len(entries), "entries": entries}


