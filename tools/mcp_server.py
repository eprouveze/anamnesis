@mcp.tool
def brief(project: str | None = None, include: list[str] | None = None) -> dict:
    """Structured startup briefing for session context.

    Returns recent decisions, known mistakes, feedback rules and capabilities. Use `project`
    to filter and `include` to select sections (decisions, mistakes, feedback, capabilities,
    topics, ontology). Top-level freshness fields describe the index; relay `index_warning`
    at session start when present.
    """
    start = time.time()
    aliases = {"recent_decisions": "decisions", "active_mistakes": "mistakes",
               "relevant_feedback": "feedback", "cross_project_context": "capabilities",
               "cross_project": "capabilities", "session_topics": "topics", "recent_topics": "topics"}
    raw = include or ["decisions", "mistakes", "feedback", "capabilities", "topics"]
    sections = [aliases.get(s, s) for s in raw]
    result: dict = {"role": ROLE, "sections": {}, **index_freshness()}

    if "decisions" in sections:
        raw_entries = _parse_raw_decisions(decisions_log_path())
        if not raw_entries:
            result["sections"]["decisions"] = []
        elif not DB_PATH.exists():
            result["sections"]["decisions"] = raw_entries[-10:]
        else:
            seen: set[str] = set()
            combined: list[str] = []

            def add(entry: str) -> None:
                if entry[:80] not in seen:
                    seen.add(entry[:80])
                    combined.append(entry)

            for entry in raw_entries[-5:]:  # recency
                add(entry)
            try:
                conn = get_db()
                try:
                    if project:  # project-specific
                        rows = conn.execute(
                            "SELECT c.title, c.content FROM chunks_fts fts JOIN chunks c ON c.id = fts.rowid "
                            "WHERE chunks_fts MATCH ? AND c.store_type = 'decision' ORDER BY rank LIMIT 10",
                            (recall_core.fts_match_query(project) or '""',)).fetchall()
                        for row in rows:
                            add(_match_full_entry(row["title"], raw_entries) or row["content"])
                    rows = conn.execute(  # universal: weight x freshness
                        "SELECT title, content, weight, modified_at FROM chunks WHERE store_type = 'decision'"
                    ).fetchall()
                finally:
                    conn.close()
                scored = sorted(
                    (((r["weight"] or 1.0) * recall_core.freshness_score(r["modified_at"] or ""),
                      r["title"], r["content"]) for r in rows),
                    key=lambda x: x[0], reverse=True)
                for _, title, content in scored[:5]:
                    add(_match_full_entry(title, raw_entries) or content)
            except sqlite3.Error as e:
                app_logger.warning("hybrid decision recall failed, using recency only: %s", e)
            result["sections"]["decisions"] = combined[:10]

    if "mistakes" in sections:
        mistakes = _read_json(manifest_dir() / "mistakes.json").get("mistakes", [])
        if project:
            mistakes = [m for m in mistakes if project.lower() in json.dumps(m).lower()]
        result["sections"]["mistakes"] = mistakes[-10:]

    if "feedback" in sections:
        feedbacks = []
        for f in sorted(memory_files_dir().glob("feedback[_-]*.md")):
            body = _strip_frontmatter(f.read_text(encoding="utf-8", errors="replace"))
            feedbacks.append({"file": f.name, "rule": body[:200]})
        result["sections"]["feedback"] = feedbacks

    if "capabilities" in sections:
        projects = _read_json(manifest_dir() / "capabilities.json").get("projects", {})
        if project:
            projects = {k: v for k, v in projects.items() if k.lower() == project.lower()}
        result["sections"]["capabilities"] = projects

    if "topics" in sections:
        topics = _read_json(manifest_dir() / "topics.json").get("topics", {})
        result["sections"]["topics"] = {k: v.get("label", k) if isinstance(v, dict) else k
                                        for k, v in topics.items()}

    if ("ontology" in sections or include is None) and DB_PATH.exists():
        try:
            conn = get_db()
            try:
                ctx = ontology.get_ambient_project_context(conn, project or DEFAULT_PROJECT)
                if ctx:
                    result["sections"]["ontology_context"] = ctx
            finally:
                conn.close()
        except Exception as e:
            app_logger.warning("ontology ambient context skipped: %s", type(e).__name__)

    audit_log("brief", f"project={project}", len(result["sections"]), (time.time() - start) * 1000)
    return result


def _strip_frontmatter(text: str) -> str:
    if text.startswith("---"):
        end = text.find("---", 3)
        if end != -1:
            return text[end + 3:].strip()
    return text


@mcp.tool
def session_context(tiers: list[int] | None = None) -> str:
    """Full dynamic core memory as markdown, for bootstrapping a session.

    Tiers (default all):
      0 = identity (DATA_DIR/identity.md, if present)
      1 = core rules (feedback memories, known mistakes)
      2 = operational context (recent sessions, recent decisions)
      3 = deep history (session topic summaries, DATA_DIR/sessions/topics/*.md)
      4 = project / reference / user memories

    Freshness: the footer states the memory index date; when the index is stale a
    "Memory index is stale" warning opens the brief. Relay it.
    """
    start = time.time()
    tiers = tiers or [0, 1, 2, 3, 4]
    idx = index_freshness()
    parts: list[str] = ["# Session Brief (via Anamnesis MCP)\n"]
    if idx.get("index_warning"):
        parts.append(f"> **Memory index is stale.** {idx['index_warning']}\n")
    mem = memory_files_dir()

    def read(path: Path) -> str:
        try:
            return path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            return ""

    def log_entries(path: Path, count: int, pattern: str) -> list[str]:
        entries = [e for e in re.split(pattern, read(path), flags=re.MULTILINE) if e.startswith("### 20")]
        out = []
        for entry in entries[-count:]:
            lines = entry.strip().split("\n")
            out.append("\n".join(lines[:20]) + ("\n  (...truncated)" if len(lines) > 20 else ""))
        return out

    if 0 in tiers:
        ident = DATA_DIR / "identity.md"
        if ident.exists():
            parts.append(read(ident))

    if 1 in tiers:
        parts.append("\n## Behavioral Rules (feedback memories)\n")
        for f in sorted(mem.glob("feedback[_-]*.md")):
            content = _strip_frontmatter(read(f))
            if content:
                parts.append(f"### {re.sub(r'^feedback[_-]', '', f.stem)}\n{content}\n")
        mistakes = _read_json(manifest_dir() / "mistakes.json").get("mistakes", [])
        if mistakes:
            parts.append("\n## Known Mistakes (most recent 20)\n")
            for m in mistakes[-20:]:
                parts.append("- " + (json.dumps(m)[:300] if not isinstance(m, dict)
                                     else str(m.get("title") or m.get("summary") or json.dumps(m)[:300])))

    if 2 in tiers:
        parts.append("\n## Recent Sessions (last 10)\n")
        for entry in log_entries(DATA_DIR / "sessions" / "log.md", 10, r"(?=^### 20\d{2}-)"):
            parts.append(entry + "\n")
        parts.append("\n## Recent Decisions (last 20)\n")
        for entry in _parse_raw_decisions(decisions_log_path())[-20:]:
            parts.append(entry + "\n")

    if 3 in tiers:
        topics_dir = DATA_DIR / "sessions" / "topics"
        if topics_dir.is_dir():
            parts.append("\n## Session Topic Summaries (compressed history)\n")
            for f in sorted(topics_dir.glob("*.md")):
                if f.name != "README.md":
                    parts.append(f"### Topic: {f.stem}\n{read(f)}\n")

    if 4 in tiers:
        for heading, prefix in (("Project Memories", "project"), ("Reference Memories", "reference"),
                                ("User Memories", "user")):
            files = sorted(mem.glob(f"{prefix}[_-]*.md"))
            if not files:
                continue
            parts.append(f"\n## {heading}\n")
            for f in files:
                text = read(f)
                desc = re.search(r"^description:\s*(.+)", text, re.MULTILINE)
                parts.append(f"### {f.stem}")
                if desc:
                    parts.append(f"_{desc.group(1)}_")
                parts.append(_strip_frontmatter(text) + "\n")

    parts.append(f"\n_Session context generated via Anamnesis MCP: {_now_iso()}_")
    parts.append(f"_Freshness: {_freshness_note(idx)}; role {idx['served_by']['role']}_")
    output = "\n".join(parts)
    audit_log("session_context", f"tiers={tiers}", len(output), (time.time() - start) * 1000)
    return output


