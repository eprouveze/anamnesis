def _log_clean(text) -> str:
    """Strip CR/LF and control characters from user-supplied text before it reaches a log."""
    return re.sub(r"[\x00-\x1f\x7f]+", " ", str(text))


def _now_iso() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def configure_logging() -> None:
    """Attach file handlers (idempotent). stderr only for the app log: stdout belongs to stdio MCP."""
    if getattr(configure_logging, "_done", False):
        return
    configure_logging._done = True  # type: ignore[attr-defined]
    LOG_DIR.mkdir(parents=True, exist_ok=True, mode=0o700)

    def private_handler(name: str) -> logging.FileHandler:
        path = LOG_DIR / name
        os.close(os.open(path, os.O_WRONLY | os.O_CREAT | os.O_APPEND, 0o600))
        os.chmod(path, 0o600)
        return logging.FileHandler(path)

    fmt_plain = logging.Formatter("%(message)s")
    for lg, fname in ((audit_logger, "audit.log"), (audit_detail_logger, "audit-detail.log")):
        h = private_handler(fname)
        h.setFormatter(fmt_plain)
        lg.addHandler(h)
    fh = private_handler("server.log")
    fh.setFormatter(logging.Formatter("%(asctime)s %(levelname)s %(message)s"))
    app_logger.addHandler(fh)
    app_logger.addHandler(logging.StreamHandler(sys.stderr))


# ---------------------------------------------------------------------------
# Client registry (clients.json: SHA-256 hashes only)
# ---------------------------------------------------------------------------
_NAME_RE = re.compile(r"^[A-Za-z0-9._-]{1,64}$")
_HEX64_RE = re.compile(r"^[0-9a-f]{64}$")
_PROCESS_MARKER = secrets.token_hex(16)        # marks AccessTokens minted by our own verifier
_LOCALHOST_TOKEN = secrets.token_urlsafe(32)   # per-process; only ever injected for loopback peers
_clients_cache: dict = {"key": None, "clients": []}


def hash_token(token: str) -> str:
    return hashlib.sha256(token.encode("utf-8")).hexdigest()


def token_fingerprint(token: str, length: int = 8) -> str:
    """Short SHA-256 prefix identifying a presented credential in logs. Never log the value."""
    return hash_token(token)[:length]


def load_clients() -> list[dict]:
    """Valid client records from CLIENTS_PATH. Missing/corrupt file -> [] (fail closed)."""
    path = CLIENTS_PATH
    try:
        st = path.stat()
    except OSError:
        return []
    key = (str(path), st.st_mtime_ns, st.st_size)
    if _clients_cache["key"] == key:
        return _clients_cache["clients"]
    clients: list[dict] = []
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
        if os.name == "posix" and st.st_mode & 0o077:
            app_logger.error("refusing to load %s: it is readable by other users (mode %o). "
                             "Run: chmod 600 %s", path, st.st_mode & 0o777, path)
            _clients_cache.update(key=key, clients=[])
            return []
        for rec in data.get("clients", []):
            name, digest, scopes = rec.get("name"), rec.get("token_sha256"), rec.get("scopes")
            if not (isinstance(name, str) and _NAME_RE.match(name)
                    and isinstance(digest, str) and _HEX64_RE.match(digest)
                    and isinstance(scopes, list) and scopes
                    and all(s in VALID_SCOPES for s in scopes)):
                app_logger.warning("ignoring malformed client record in %s", path)
                continue
            clients.append({"name": name, "token_sha256": digest, "scopes": list(scopes)})
    except (OSError, ValueError, AttributeError) as e:
        app_logger.error("cannot read clients file %s: %s", path, type(e).__name__)
        clients = []
    _clients_cache.update(key=key, clients=clients)
    return clients


def find_client(token: str) -> dict | None:
    """Constant-time lookup: every stored hash is compared, no early exit on a match."""
    if not token or len(token) > 512:
        return None
    presented = hash_token(token).encode("ascii")
    match = None
    for c in load_clients():
        if hmac.compare_digest(c["token_sha256"].encode("ascii"), presented):
            match = c
    return match


def _write_clients(path: Path, records: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.name}.{secrets.token_hex(8)}.tmp")
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_NOFOLLOW", 0), 0o600)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            json.dump({"clients": records}, f, indent=2)
            f.write("\n")
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise
    _clients_cache["key"] = None


def _raw_client_records(path: Path) -> list[dict]:
    if not path.exists():
        return []
    return list(json.loads(path.read_text(encoding="utf-8")).get("clients", []))


def add_client(name: str, read_only: bool = False, path: Path | None = None) -> str:
    """Create a client and return its token. The token is NOT stored; only its hash is."""
    path = path or CLIENTS_PATH
    if not _NAME_RE.match(name):
        raise ValueError("client name must match [A-Za-z0-9._-]{1,64}")
    records = _raw_client_records(path)
    if any(r.get("name") == name for r in records):
        raise ValueError(f"client '{name}' already exists (revoke it first to rotate)")
    token = "anm_" + secrets.token_urlsafe(32)
    records.append({
        "name": name,
        "token_sha256": hash_token(token),
        "scopes": ["read"] if read_only else ["read", "write"],
        "created_at": _now_iso(),
    })
    _write_clients(path, records)
    return token


def revoke_client(name: str, path: Path | None = None) -> bool:
    path = path or CLIENTS_PATH
    records = _raw_client_records(path)
    kept = [r for r in records if r.get("name") != name]
    if len(kept) == len(records):
        return False
    _write_clients(path, kept)
    return True


class ClientTokenVerifier(TokenVerifier):
    """fastmcp TokenVerifier backed by clients.json (and the opt-in loopback token)."""

    async def verify_token(self, token: str) -> AccessToken | None:
        client = find_client(token)
        if client:
            return AccessToken(
                token=token, client_id=client["name"], scopes=list(client["scopes"]),
                claims={"anamnesis_marker": _PROCESS_MARKER, "anamnesis_client": client["name"]},
            )
        if _flag("ANAMNESIS_ALLOW_LOCALHOST_NOAUTH") and token and \
                hmac.compare_digest(token.encode("utf-8"), _LOCALHOST_TOKEN.encode("utf-8")):
            scopes = ["read", "write"] if _flag("ANAMNESIS_LOCALHOST_WRITE") else ["read"]
            return AccessToken(
                token=token, client_id="localhost", scopes=scopes,
                claims={"anamnesis_marker": _PROCESS_MARKER, "anamnesis_client": "localhost"},
            )
        return None


# ---------------------------------------------------------------------------
# Optional OAuth (claude.ai / ChatGPT custom connectors)
# ---------------------------------------------------------------------------
# fastmcp 4.1.8 ships OAuth proxy providers for Google, GitHub, Auth0, Azure, WorkOS, ...
# (fastmcp/server/auth/providers/*.py). GoogleProvider/GitHubProvider are OAuthProxy
# subclasses that run the full MCP OAuth flow (DCR, PKCE, consent page) in front of the
# upstream IdP. MultiAuth (fastmcp/server/auth/auth.py) composes ONE such server with
# extra TokenVerifiers on the same endpoint: it tries the server first, then each
# verifier. That is exactly "OAuth for GUI connectors + static bearer for headless
# clients". We expose Google and GitHub; any other OAuthProxy provider could be added
# the same way.
#
# OAuth proves identity, not authorization: any Google/GitHub account can complete the
# flow. The allowlist is therefore enforced server-side on every tool call
# (ToolAuthMiddleware), never delegated to the IdP or the client.

def _csv_env(name: str) -> list[str]:
    return [p.strip() for p in os.environ.get(name, "").split(",") if p.strip()]


def oauth_provider_name() -> str | None:
    name = os.environ.get("ANAMNESIS_OAUTH_PROVIDER", "").strip().lower()
    if not name:
        return None
    if name not in ("google", "github"):
        raise SystemExit(f"ANAMNESIS_OAUTH_PROVIDER must be google or github, got {name!r}")
    return name


def oauth_allowlist() -> set[str]:
    key = "ANAMNESIS_OAUTH_ALLOWED_EMAILS" if oauth_provider_name() == "google" \
        else "ANAMNESIS_OAUTH_ALLOWED_LOGINS"
    return {v.lower() for v in _csv_env(key)}


def oauth_scopes() -> list[str]:
    scopes = [s for s in (_csv_env("ANAMNESIS_OAUTH_SCOPES") or ["read"]) if s in VALID_SCOPES]
    return scopes or ["read"]


def build_oauth_provider(client_storage=None):
    """The fastmcp OAuth provider selected by env, or None. Fails closed on a bad config."""
    name = oauth_provider_name()
    if name is None:
        return None
    client_id = os.environ.get("ANAMNESIS_OAUTH_CLIENT_ID", "")
    client_secret = os.environ.get("ANAMNESIS_OAUTH_CLIENT_SECRET", "")
    base_url = os.environ.get("ANAMNESIS_OAUTH_BASE_URL", "")
    if not (client_id and client_secret and base_url):
        raise SystemExit("OAuth needs ANAMNESIS_OAUTH_CLIENT_ID, ANAMNESIS_OAUTH_CLIENT_SECRET "
                         "and ANAMNESIS_OAUTH_BASE_URL (the public https URL of this server)")
    if not oauth_allowlist():
        raise SystemExit("OAuth refused to start: the allowlist is empty "
                         "(ANAMNESIS_OAUTH_ALLOWED_EMAILS / ANAMNESIS_OAUTH_ALLOWED_LOGINS). "
                         "Without it any Google/GitHub account could read your memory.")
    kwargs = dict(client_id=client_id, client_secret=client_secret, base_url=base_url,
                  jwt_signing_key=os.environ.get("ANAMNESIS_OAUTH_JWT_KEY") or None)
    if client_storage is not None:
        kwargs["client_storage"] = client_storage
    if name == "google":
        from fastmcp.server.auth.providers.google import GoogleProvider
        # The email scope is what makes tokeninfo/userinfo return the address we check.
        return GoogleProvider(required_scopes=["openid", "https://www.googleapis.com/auth/userinfo.email"],
                              **kwargs)
    from fastmcp.server.auth.providers.github import GitHubProvider
    return GitHubProvider(**kwargs)


def build_auth(oauth_storage=None):
    """Auth provider for the HTTP transport: static client tokens, plus OAuth if configured."""
    verifier = ClientTokenVerifier()
    oauth = build_oauth_provider(oauth_storage)
    if oauth is None:
        return verifier
    # required_scopes=[] stops MultiAuth inheriting the IdP's scopes (openid, email, ...)
    # as a requirement on EVERY token, which would reject static tokens whose scopes are
    # read/write. The IdP provider still validates its own tokens.
    return MultiAuth(server=oauth, verifiers=[verifier], required_scopes=[])


# ---------------------------------------------------------------------------
# Principals and per-call authorization
# ---------------------------------------------------------------------------
@dataclass(frozen=True)
class Principal:
    name: str
    scopes: frozenset
    via: str  # stdio | token | oauth

    @property
    def can_write(self) -> bool:
        return "write" in self.scopes


_current_principal: contextvars.ContextVar[Principal | None] = contextvars.ContextVar(
    "anamnesis_principal", default=None)
# Explicit transport marker. "stdio" is set only by the stdio entry point; build_http_app sets
# "http". Anything else (unset, in-process) fails closed rather than being trusted.
_TRANSPORT: str | None = None


def _truthy(v) -> bool:
    return v is True or str(v).lower() == "true"


def principal_from_access_token(at: AccessToken) -> Principal:
    claims = at.claims or {}
    if claims.get("anamnesis_marker") == _PROCESS_MARKER:
        return Principal(str(claims.get("anamnesis_client", "unknown")), frozenset(at.scopes or []), "token")
    provider = oauth_provider_name()
    allowed = oauth_allowlist() if provider else set()
    if provider == "google":
        ident = claims.get("email")
        ok = bool(ident) and _truthy(claims.get("email_verified"))
    elif provider == "github":
        ident = claims.get("login")
        ok = bool(ident)
        # Logins can be renamed and re-registered by someone else; "id:<numeric>" entries match
        # the stable account id (the token's `sub`) and are the safe way to allowlist.
        sub = claims.get("sub")
        if sub is not None and f"id:{sub}" in allowed:
            return Principal(f"github:{ident or sub}", frozenset(oauth_scopes()), "oauth")
    else:
        ident, ok = None, False
    if not (ok and str(ident).lower() in allowed):
        raise ToolError("This account is not authorized to use this server")
    return Principal(f"{provider}:{ident}", frozenset(oauth_scopes()), "oauth")


def resolve_principal() -> Principal:
    try:
        get_http_request()
        has_request = True
    except Exception:
        has_request = False
    if not has_request:
        if _TRANSPORT == "stdio":
            return Principal("stdio", frozenset(VALID_SCOPES), "stdio")  # trusted local process
        raise ToolError("Authentication required")
    at = get_access_token()
    if at is None:
        raise ToolError("Authentication required")
    return principal_from_access_token(at)


class ToolAuthMiddleware(Middleware):
    """Authorize every tool call: resolve who is calling, enforce write scope."""

    async def on_call_tool(self, context: MiddlewareContext, call_next):
        principal = resolve_principal()
        tool_name = context.message.name
        need = required_scope(tool_name)
        if need not in principal.scopes:
            _bump(_auth_stats["by_reason"], "scope_denied")
            app_logger.warning("scope denied: client=%s tool=%s needs=%s", _log_clean(principal.name),
                               _log_clean(tool_name), need)
            raise ToolError("This client has read-only access" if need == "write"
                            else "This client lacks the read scope")
        token = _current_principal.set(principal)
        try:
            return await call_next(context)
        finally:
            _current_principal.reset(token)


# ---------------------------------------------------------------------------
# HTTP-layer pre-auth: query-token handling, opt-in loopback, failure telemetry
# ---------------------------------------------------------------------------
_auth_stats: dict = {"failures": 0, "by_transport": {}, "by_reason": {}, "last_failure_at": None}
_PROXY_HEADERS = frozenset({b"x-forwarded-for", b"x-forwarded-host", b"x-forwarded-proto", b"x-real-ip",
                            b"forwarded", b"cf-connecting-ip", b"true-client-ip", b"via"})


def _bump(counter: dict, key: str) -> None:
    counter[key] = counter.get(key, 0) + 1


def _is_loopback_peer(scope) -> bool:
    client = scope.get("client")
    return bool(client) and client[0] in ("127.0.0.1", "::1", "::ffff:127.0.0.1")


class PreAuthMiddleware:
    """ASGI wrapper that runs BEFORE fastmcp's bearer authentication on /mcp requests.

    * `?token=` in the URL: rejected with 401 unless ANAMNESIS_ALLOW_QUERY_TOKEN=1, in which
      case it is moved into the Authorization header and stripped from the query string.
    * Opt-in loopback: with ANAMNESIS_ALLOW_LOCALHOST_NOAUTH=1, a direct loopback request
      with no credentials and no proxy headers gets a per-process internal token.
    * Logs one redacted line per 401 (credential fingerprint only, never the value).
    Other paths (/health, OAuth endpoints) pass through untouched.
    """

    def __init__(self, app, mcp_path: str = "/mcp"):
        self.app = app
        self.mcp_path = mcp_path

    async def __call__(self, scope, receive, send):
        if scope["type"] != "http" or not scope.get("path", "").startswith(self.mcp_path):
            await self.app(scope, receive, send)
            return

        headers = list(scope.get("headers", []))
        names = {k for k, _ in headers}
        auth_value = next((v for k, v in headers if k == b"authorization"), b"").decode("latin-1")
        transport = "header" if auth_value else "none"
        presented = auth_value[7:].strip() if auth_value.lower().startswith("bearer ") else ""

        pairs = parse_qsl(scope.get("query_string", b"").decode("latin-1"), keep_blank_values=True)
        has_token_param = any(k == "token" for k, _ in pairs)
        qtoken = next((v for k, v in pairs if k == "token" and v.strip()), "")
        if qtoken and not _flag("ANAMNESIS_ALLOW_QUERY_TOKEN"):
            # Rejected even when a valid Authorization header is also present.
            _bump(_auth_stats["by_reason"], "query_token_disabled")
            self._record(scope, "query", "query_token_disabled", qtoken)
            resp = JSONResponse(
                {"error": "query_token_disabled",
                 "detail": "Send the token as 'Authorization: Bearer <token>'. "
                           "URL tokens leak into logs and configs."},
                status_code=401, headers={"WWW-Authenticate": "Bearer"})
            await resp(scope, receive, send)
            return
        if has_token_param:
            # Never forward a token-shaped query parameter downstream (logs, request.url).
            rest = urlencode([(k, v) for k, v in pairs if k != "token"]).encode("latin-1")
            scope = dict(scope, query_string=rest)
        if not auth_value:
            if qtoken:
                app_logger.warning("SECURITY: credential accepted from URL query string (client=%s, token_sha256_8=%s); "
                                   "ANAMNESIS_ALLOW_QUERY_TOKEN is on, prefer the Authorization header",
                                   _log_clean((scope.get("client") or ["?"])[0]), token_fingerprint(qtoken))
                scope = dict(scope, headers=headers + [(b"authorization", b"Bearer " + qtoken.encode("latin-1"))])
                transport, presented = "query", qtoken
            elif _flag("ANAMNESIS_ALLOW_LOCALHOST_NOAUTH") and _is_loopback_peer(scope) \
                    and not (names & _PROXY_HEADERS):
                scope = dict(scope, headers=headers + [(b"authorization", b"Bearer " + _LOCALHOST_TOKEN.encode())])
                transport = "localhost"

        async def send_wrapper(message):
            if message["type"] == "http.response.start" and message["status"] in (401, 403):
                self._record(scope, transport, "rejected" if presented else "no_credential", presented)
            await send(message)

        await self.app(scope, receive, send_wrapper)

    @staticmethod
    def _record(scope, transport: str, reason: str, credential: str) -> None:
        _auth_stats["failures"] += 1
        _bump(_auth_stats["by_transport"], transport)
        _bump(_auth_stats["by_reason"], reason)
        _auth_stats["last_failure_at"] = _now_iso()
        ua = next((v for k, v in scope.get("headers", []) if k == b"user-agent"), b"").decode("latin-1")[:60]
        level = logging.WARNING if credential else logging.INFO
        app_logger.log(level, json.dumps({
            "event": "auth_failure", "ts": _now_iso(), "path": scope.get("path"), "transport": transport,
            "reason": reason, "client_host": (scope.get("client") or [None])[0], "user_agent": ua or None,
            "credential_len": len(credential),
            "credential_sha256_8": token_fingerprint(credential) if credential else None,
        }))


class McpConcurrencyLimitMiddleware:
    """Cap concurrent /mcp requests so a retry storm cannot starve /health.

    A single uvicorn worker shares one event loop between /mcp and /health; unbounded
    /mcp concurrency can leave /health unscheduled. Overflow gets an immediate 503
    (no MCP session machinery is entered). /health is never gated. The counter needs no
    lock: there is no await between check and increment.
    """

    def __init__(self, app, max_concurrent: int = 20):
        self.app = app
        self.max_concurrent = max_concurrent
        self._current = 0

    async def __call__(self, scope, receive, send):
        if scope["type"] != "http" or not scope.get("path", "").startswith("/mcp"):
            await self.app(scope, receive, send)
            return
        if self._current >= self.max_concurrent:
            resp = JSONResponse({"error": "mcp_overloaded",
                                 "detail": "too many concurrent /mcp requests, retry with backoff"},
                                status_code=503)
            await resp(scope, receive, send)
            return
        self._current += 1
        try:
            await self.app(scope, receive, send)
        finally:
            self._current -= 1


