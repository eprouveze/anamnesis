def _chunk_summary(row: sqlite3.Row | dict) -> dict:
    d = dict(row)
    summary = {
        "id": d.get("id"), "chunk_id": d.get("chunk_id"), "title": d.get("title"),
        "store_type": d.get("store_type"), "project": d.get("project"),
        "source_path": _public_path(d.get("source_path")),
        "content_preview": (d.get("content") or "")[:240],
    }
