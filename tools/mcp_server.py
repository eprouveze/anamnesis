def _resolve_chunk_id(conn: sqlite3.Connection, ident) -> int | None:
    """Accept chunks.id (int) or chunks.chunk_id (str); return the int id."""
    if isinstance(ident, int):
        row = conn.execute("SELECT id FROM chunks WHERE id = ?", (ident,)).fetchone()
        return row["id"] if row else None
    if isinstance(ident, str):
        if ident.isdigit():
            return _resolve_chunk_id(conn, int(ident))
        row = conn.execute("SELECT id FROM chunks WHERE chunk_id = ?", (ident,)).fetchone()
        return row["id"] if row else None
    return None


def _walk_links(conn: sqlite3.Connection, start_id: int, direction: str, max_hops: int) -> list[dict]:
    """BFS over nugget_links. direction in {forward, backward, both}.

    Edges whose target chunk does not exist (to_chunk_id NULL) are surfaced as terminal
    nodes carrying relation_type + source_text; BFS cannot traverse past them.
    """
    visited: set[int] = {start_id}
    edges: list[dict] = []
    frontier: list[tuple[int, int]] = [(start_id, 0)]
    valid_clause = validity.link_validity_clause(conn, "nl")  # '' unless bi-temporal validity is live
    has_coords = ontology.has_nugget_link_coord_columns(conn)
    while frontier:
        node_id, hop = frontier.pop(0)
        if hop >= max_hops:
            continue
        queries: list[tuple[str, tuple]] = []
        if direction in ("forward", "both"):
            if has_coords:
                queries.append((
                    "SELECT nl.*, COALESCE(c.id, ck.id) AS resolved_target_int_id, "
                    "COALESCE(c.chunk_id, ck.chunk_id) AS target_chunk_id, "
                    "COALESCE(c.title, ck.title) AS target_title, "
                    "COALESCE(c.store_type, ck.store_type) AS target_store_type, "
                    "COALESCE(c.project, ck.project) AS target_project "
                    "FROM nugget_links nl "
                    "LEFT JOIN chunks c ON c.id = nl.to_chunk_id "
                    "LEFT JOIN chunks ck ON (c.id IS NULL AND nl.to_chunk_key IS NOT NULL AND ck.chunk_key = nl.to_chunk_key) "
                    "WHERE nl.from_chunk_id = ?" + valid_clause, (node_id,)))
            else:
                queries.append((
                    "SELECT nl.*, c.id AS resolved_target_int_id, c.chunk_id AS target_chunk_id, "
                    "c.title AS target_title, c.store_type AS target_store_type, c.project AS target_project "
                    "FROM nugget_links nl LEFT JOIN chunks c ON c.id = nl.to_chunk_id "
                    "WHERE nl.from_chunk_id = ?" + valid_clause, (node_id,)))
        if direction in ("backward", "both"):
            queries.append((
                "SELECT nl.*, c.id AS resolved_target_int_id, c.chunk_id AS target_chunk_id, "
                "c.title AS target_title, c.store_type AS target_store_type, c.project AS target_project "
                "FROM nugget_links nl LEFT JOIN chunks c ON c.id = nl.from_chunk_id "
                "WHERE nl.to_chunk_id = ?" + valid_clause, (node_id,)))
        for sql, params in queries:
            for row in conn.execute(sql, params).fetchall():
                keys = row.keys()
                target_exists = row["target_chunk_id"] is not None
                target_int_id = row["resolved_target_int_id"] if target_exists else None
                status = (row["resolution_status"] if ("resolution_status" in keys and row["resolution_status"])
                          else ("resolved" if target_exists else "unresolved"))
                is_resolved = bool(target_exists and status != "unresolved")
                edges.append({
                    "hop": hop + 1, "link_id": row["id"], "from_chunk_id": row["from_chunk_id"],
                    "to_chunk_id": target_int_id, "relation_type": row["relation_type"],
                    "confidence": row["confidence"], "source_text": row["source_text"],
                    "resolution_status": status if target_exists else "unresolved",
                    "resolved": is_resolved,
                    "target": ({"id": target_int_id, "chunk_id": row["target_chunk_id"],
                                "title": row["target_title"], "store_type": row["target_store_type"],
                                "project": row["target_project"]} if is_resolved else None),
                })
                if is_resolved and target_int_id is not None and target_int_id not in visited:
                    visited.add(target_int_id)
                    frontier.append((target_int_id, hop + 1))
    return edges


@mcp.tool
def recall_precedent(query: str, depth: int = 1, limit: int = 5) -> list[dict]:
    """Recall + graph walk: for each top match, surface linked precedents and successors.

    Runs `recall(query)` for the top `limit` chunks, then walks `nugget_links` up to `depth`
    hops (max 3) in both directions. Edges with a NULL target (unresolved prose references)
    surface as terminal nodes carrying relation_type and source_text.

    Use for queries like "show failed approaches whose fix later caused another failure":
    the top match is the failed approach, the linked successors are chunks linked by
    `fixed_by` / `caused_by` edges. Each match carries recall's freshness fields.
    """
    depth = max(0, min(depth, 3))
    limit = max(1, min(limit, 20))
    matches = _recall_impl(query, limit=limit)
    if not matches or "error" in matches[0] or "message" in matches[0]:
        return matches
    conn = get_db()
    try:
        out: list[dict] = []
        for m in matches:
            start_id = _resolve_chunk_id(conn, m.get("chunk_id"))
            if start_id is None:
                out.append({**m, "linked_edges": [], "note": "chunk row not found"})
                continue
            edges = _walk_links(conn, start_id, "both", depth) if depth > 0 else []
            out.append({**m, "linked_edges": edges, "linked_edge_count": len(edges),
                        "linked_resolved_count": sum(1 for e in edges if e["resolved"])})
    finally:
        conn.close()
    audit_log("recall_precedent", query, len(out), 0.0)
    return out


@mcp.tool
def trace(chunk_id: int | str, direction: str = "both", max_hops: int = 3) -> dict:
    """Walk the nugget_links graph from a starting chunk.

    Args:
      chunk_id:  the int row id (chunks.id) or the string chunk_id.
      direction: 'forward' (this chunk -> consequences), 'backward' (-> precedents) or 'both'.
      max_hops:  stop after this many hops (default 3, max 6).

    Returns the starting chunk, the discovered edges and a `stopped_reason`. Edges with a
    NULL target are included as terminal leaves with their relation_type and original prose.
    Top-level freshness fields describe the index; `start.source_date` is the chunk's own date.
    """
    if direction not in ("forward", "backward", "both"):
        raise ToolError(f"direction must be 'forward'|'backward'|'both', got {direction!r}")
    max_hops = max(0, min(max_hops, 6))
    if not DB_PATH.exists():
        return {"error": _NO_INDEX}
    conn = get_db()
    try:
        start_id = _resolve_chunk_id(conn, chunk_id)
        if start_id is None:
            return {"error": f"chunk_id {chunk_id!r} not found"}
        start_row = conn.execute("SELECT * FROM chunks WHERE id = ?", (start_id,)).fetchone()
        edges = _walk_links(conn, start_id, direction, max_hops)
        unresolved = sum(1 for e in edges if not e["resolved"])
        stopped = ("no_more_links" if not edges
                   else ("all_unresolved" if unresolved == len(edges) else "max_hops_or_no_more_links"))
        start = _chunk_summary(start_row)
        start["source_date"] = _source_date(dict(start_row))
        return {"start": start, "direction": direction, "max_hops": max_hops, "edge_count": len(edges),
                "resolved_count": len(edges) - unresolved, "unresolved_count": unresolved,
                "edges": edges, "stopped_reason": stopped, **index_freshness()}
    finally:
        conn.close()


@mcp.tool
def ontology_impact(entity_id: str, mode: str = "failure", depth: int = 2,
                    include_evidence: bool = True) -> dict:
    """Inspect an operational entity or compute its dependency and failure blast radius.

    Args:
      entity_id: canonical ID or alias (e.g. 'service/search-api', 'search-api').
      mode:      'failure' (blast radius, single points of failure, fallbacks, past incidents),
                 'dependencies' (upstream/downstream walk) or 'inspect' (node attributes,
                 direct claims, prose evidence).
      depth:     maximum traversal hops (1..5, default 2).
      include_evidence: attach resolved prose chunks from ontology_evidence.
    """
    start = time.time()
    depth = max(1, min(depth, 5))
    if mode not in ("failure", "dependencies", "inspect"):
        raise ToolError(f"mode must be 'failure'|'dependencies'|'inspect', got {mode!r}")
    if not DB_PATH.exists():
        return {"error": _NO_INDEX}
    conn = get_db()
    try:
        res = ontology.query_ontology_impact(conn, entity_id=entity_id, mode=mode, depth=depth,
                                             include_evidence=include_evidence)
    finally:
        conn.close()
    audit_log("ontology_impact", f"{entity_id}:{mode}", 1, (time.time() - start) * 1000)
    return {**res, **index_freshness()}


