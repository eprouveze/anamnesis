# ---------------------------------------------------------------------------
# Answer freshness: every read tool says how current the index is
# ---------------------------------------------------------------------------
# MAX(chunks.indexed_at) cannot reveal a dead batch indexer, because store_memory /
# store_decision insert rows with indexed_at=now. The indexer's own signal is
# index_meta 'last_updated', written only by index.py's update/build. That is what the
# read tools report. Cost: one primary-key lookup + one stat(), cached for
# INDEX_FRESHNESS_TTL_S; never an aggregate over chunks.
_index_freshness_cache: dict = {"at": None, "updated": None, "db_mtime": None}


def _parse_ts(value) -> datetime | None:
    if not value:
        return None
    try:
        dt = datetime.fromisoformat(str(value).strip().replace("Z", "+00:00"))
    except ValueError:
        return None
    return (dt if dt.tzinfo else dt.replace(tzinfo=timezone.utc)).astimezone(timezone.utc)


def _fmt_utc(dt: datetime | None) -> str | None:
    return dt.strftime("%Y-%m-%dT%H:%M:%SZ") if dt else None


def _read_index_freshness_raw() -> tuple[str | None, float | None]:
    updated, mtime = None, None
    try:
        mtime = DB_PATH.stat().st_mtime
    except OSError:
        pass
    try:
        conn = sqlite3.connect(DB_PATH.resolve().as_uri() + "?mode=ro", uri=True, timeout=1.0)
        try:
            row = conn.execute("SELECT value FROM index_meta WHERE key = 'last_updated'").fetchone()
            updated = row[0] if row else None
        finally:
            conn.close()
    except sqlite3.Error:
        pass
    return updated, mtime


def index_freshness(now: datetime | None = None) -> dict:
    """index_updated_at / index_age_h / index_stale / served_by (+ index_warning when stale)."""
    cache = _index_freshness_cache
    mono = time.monotonic()
    if cache["at"] is None or mono - cache["at"] >= INDEX_FRESHNESS_TTL_S:
        cache["updated"], cache["db_mtime"] = _read_index_freshness_raw()
        cache["at"] = mono
    return _compose_freshness(cache["updated"], cache["db_mtime"], now)


def _compose_freshness(updated_raw, db_mtime, now: datetime | None = None) -> dict:
    now = now or datetime.now(timezone.utc)
    updated = _parse_ts(updated_raw)
    age_h = round((now - updated).total_seconds() / 3600, 1) if updated else None
    stale = age_h is None or age_h > INDEX_STALE_AFTER_H
    served_by: dict = {"role": ROLE}
    if ROLE == "replica" and db_mtime is not None:
        served_by["replica_synced_at"] = _fmt_utc(datetime.fromtimestamp(db_mtime, timezone.utc))
    out = {"index_updated_at": _fmt_utc(updated), "index_age_h": age_h,
           "index_stale": stale, "served_by": served_by}
    if stale:
        if updated:
            ago = f"{age_h / 24:.1f} days ago" if age_h >= 48 else f"{age_h:.1f} hours ago"
            msg = (f"Memory index last updated {updated.strftime('%Y-%m-%d %H:%M')} UTC ({ago}): "
                   "anything after that is missing from these results.")
        else:
            msg = ("Memory index update time is unknown (index_meta.last_updated missing): "
                   "treat these results as possibly out of date.")
        if ROLE == "replica":
            msg += " Served by a read-only replica" + (
                f", last synced {served_by['replica_synced_at']}." if "replica_synced_at" in served_by else ".")
        out["index_warning"] = msg
    return out


def _freshness_note(f: dict) -> str:
    when = f["index_updated_at"] or "unknown"
    age = f", {f['index_age_h']} h ago" if f["index_age_h"] is not None else ""
    return f"memory index as of {when}{age}"


_DATE_RE = re.compile(r"\d{4}-\d{2}-\d{2}")


def _source_date(row: dict) -> str | None:
    """The source's own date: source_session_at, else a YYYY-MM-DD in the title (log entries
    are headed '### 2026-03-17 - ...'), else modified_at. Not indexed_at: that is when the
    indexer saw the source, not when it happened."""
    if row.get("source_session_at"):
        return row["source_session_at"]
    m = _DATE_RE.search(row.get("title") or "")
    return m.group() if m else (row.get("modified_at") or None)


def _no_results(query: str, idx: dict) -> dict:
    """The empty-result element: keeps the 'No results for:' prefix and epistemic_gap flag
    callers match on, and names the index date because a miss on a stale index proves nothing."""
    return {"message": f"No results for: {query} ({_freshness_note(idx)})", "epistemic_gap": True, **idx}


