_NO_INDEX = "Memory index not built. Run: python tools/index.py"


def _recall_impl(query: str, limit: int = 10, store_types: list[str] | None = None,
                 project: str | None = None) -> list[dict]:
    start = time.time()
    if not DB_PATH.exists():
        return [{"error": _NO_INDEX}]
    idx = index_freshness()
    limit = max(1, min(limit, 50))
    conn = get_db()
    try:
        rows, info = recall_core.search_chunks(conn, query, limit=limit, store_types=store_types,
                                               project=project, embed=_embedder())
    finally:
        conn.close()
    if info.get("embed_error"):
        app_logger.warning("embedding failed, falling back to FTS-only: %s", info["embed_error"])
    latency = (time.time() - start) * 1000
    if not rows:
        audit_log("recall", query, 0, latency)
        return [_no_results(query, idx)]

    results = []
    for r in rows:
        item = {
            "chunk_id": r["chunk_id"], "title": r["title"], "content": r["content"][:500],
            "source_path": _public_path(r["source_path"]), "store_type": r["store_type"],
            "project": r.get("project") or "", "score": r["score"], "similarity": r["similarity"],
            "freshness": r["freshness"], "confidence": r["confidence"],
            "source_date": _source_date(r), **idx,
        }
        if r["store_type"] == "decision":
            _with_decision_fields(item, r["content"])
        results.append(item)
    if results[0]["similarity"] < 0.35:
        for item in results:
            item["epistemic_gap"] = True
    audit_log("recall", query, len(results), latency, details=results)
    return results


@mcp.tool
def recall(query: str, limit: int = 10, store_types: list[str] | None = None,
           project: str | None = None) -> list[dict]:
    """Search memory by MEANING (FTS5 keyword candidates + embedding rerank).

    Returns chunks ranked by semantic similarity, with source, score, store_type and
    confidence. Use for "what do we know about X", "why did we decide Y", "past work on Z":
    questions where you know the TOPIC.

    DO NOT use for recency questions ("what's the latest", "what did we just build"). This
    tool has no time ordering; call `get_recent` instead. Never invent a topic to search
    for when the user is really asking what is newest.

    FRESHNESS (relay it): each result carries `source_date` (when the source itself was
    written) and the index currency: `index_updated_at` (UTC), `index_age_h`, `index_stale`,
    `served_by`. When the index is stale (> ANAMNESIS_INDEX_STALE_H, default 30 h) each result
    also has `index_warning`; pass that sentence to the human verbatim. `freshness` is only a
    0-1 ranking decay score, not a date. A "No results for: ..." reply names the index date: a
    miss on a stale index proves nothing.
    """
    return _recall_impl(query, limit, store_types, project)


@mcp.tool
def get_recent(limit: int = 10, store_types: list[str] | None = None,
               project: str | None = None) -> list[dict]:
    """Return the MOST RECENT memory entries, newest first: by time, not relevance.

    THIS is the tool for recency questions ("what's the latest", "what did we just build",
    "what happened recently"). It does no semantic search, so it cannot be misled by a
    guessed query. Defaults to the activity log (session_topic + decision); pass store_types
    to widen (e.g. ["session_topic", "decision", "memory"]) or project to filter.

    FRESHNESS: "most recent" means most recent IN THE INDEX. Results carry `source_date` plus
    the index freshness fields; when `index_warning` is present the newest entry shown is not
    necessarily the newest that exists. Say so, citing the index date.
    """
    start = time.time()
    if not DB_PATH.exists():
        return [{"error": _NO_INDEX}]
    idx = index_freshness()
    types = store_types or ["session_topic", "decision"]
    conn = get_db()
    try:
        # source_session_at is added by optional forensics indexers, so older DBs may lack it.
        has_ssa = any(r[1] == "source_session_at" for r in conn.execute("PRAGMA table_info(chunks)"))
        ssa_col = "source_session_at" if has_ssa else "NULL AS source_session_at"
        sql = (f"SELECT id, title, content, store_type, source_path, project, modified_at, {ssa_col} "
               f"FROM chunks WHERE store_type IN ({','.join('?' for _ in types)})")
        params: list = list(types)
        if project:
            sql += " AND project = ?"
            params.append(project)
        # Logs are append-only, so autoincrement id tracks chronology better than modified_at
        # (which is just the last reindex date).
        sql += " ORDER BY id DESC LIMIT ?"
        params.append(max(1, min(limit, 50)))
        rows = conn.execute(sql, params).fetchall()
    finally:
        conn.close()

    results = []
    for row in rows:
        d = dict(row)
        title, content = d.get("title") or "", d.get("content") or ""
        m = _DATE_RE.search(title) or _DATE_RE.search(content)
        item = {
            "date": m.group() if m else (d.get("modified_at") or "unknown"),
            "title": title[:140], "store_type": d.get("store_type"), "project": d.get("project"),
            "source_path": _public_path(d.get("source_path")), "snippet": content[:300],
            "source_date": d.get("source_session_at") or (m.group() if m else d.get("modified_at")),
            **idx,
        }
        if d.get("store_type") == "decision":
            _with_decision_fields(item, content)
        results.append(item)
    audit_log("get_recent", f"types={types} project={project} limit={limit}", len(results),
              (time.time() - start) * 1000)
    if not results:
        return [{"message": f"No recent entries for types={types} project={project} ({_freshness_note(idx)})",
                 "epistemic_gap": True, **idx}]
    return results


