def _refuse_if_replica(what: str) -> None:
    if ROLE == "replica":
        raise ToolError(f"Read-only replica: this server's database is replaced by its next sync. "
                        f"Persist the {what} to the source repository instead (it is indexed by the "
                        "primary). Promote this server to a writer with ANAMNESIS_ROLE=primary.")


def _one_line(text: str, limit: int = 200) -> str:
    return re.sub(r"\s+", " ", text).strip()[:limit]


_HEADING_LINE = re.compile(r"^([ \t]*)#", re.MULTILINE)


def _defang_log_text(text: str) -> str:
    """Make user text safe to embed in decisions/log.md.

    The log is split into entries at lines starting with '### <date>' and parsed by
    '**Field:**' markers (anywhere a line starts with one, after stripping whitespace), so a
    value containing such a line could forge a backdated entry or override a field such as
    Decision, Supersedes or Origin. Every '**' is escaped and any line starting with '#' gets
    a backslash, so neither parser can match them; Markdown still renders the literal text.
    CR is normalised to LF.
    """
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    text = text.replace("**", "\\*\\*")
    return _HEADING_LINE.sub(lambda m: m.group(1) + "\\#", text)


def _slug(title: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", title.lower())[:50].strip("_") or "untitled"


def _git_autocommit(path: Path, message: str) -> bool:
    if not _flag("ANAMNESIS_GIT_AUTOCOMMIT"):
        return False
    try:
        repo = subprocess.check_output(["git", "rev-parse", "--show-toplevel"], cwd=str(path.parent),
                                       stderr=subprocess.DEVNULL, timeout=10).decode().strip()
        subprocess.run(["git", "add", "--", str(path)], cwd=repo, check=True, timeout=10)
        subprocess.run(["git", "commit", "-m", message, "--", str(path)], cwd=repo, check=True,
                       capture_output=True, timeout=30)
        return True
    except Exception as e:
        app_logger.warning("git autocommit failed: %s", type(e).__name__)
        return False


def _insert_chunk(conn: sqlite3.Connection, row: dict) -> None:
    """Insert a chunk so it is searchable immediately (no embedding until the next index run).

    If the schema has the chunks_ai trigger it already feeds chunks_fts; otherwise we do.
    """
    conn.execute(
        "INSERT INTO chunks (chunk_id, store_type, source_path, title, content, created_at, modified_at,"
        " project, topic_ids, weight, indexed_at) VALUES (?,?,?,?,?,?,?,?,?,?,?)",
        (row["chunk_id"], row["store_type"], row["source_path"], row["title"], row["content"],
         row["now"], row["now"], row["project"], row["topic_ids"], row["weight"], row["now"]))
    has_trigger = conn.execute(
        "SELECT 1 FROM sqlite_master WHERE type='trigger' AND name='chunks_ai'").fetchone()
    if not has_trigger:
        rid = conn.execute("SELECT id FROM chunks WHERE chunk_id = ?", (row["chunk_id"],)).fetchone()[0]
        conn.execute("INSERT INTO chunks_fts(rowid, chunk_id, title, content, store_type, project, topic_ids)"
                     " VALUES (?,?,?,?,?,?,?)",
                     (rid, row["chunk_id"], row["title"], row["content"], row["store_type"],
                      row["project"], row["topic_ids"]))


def _chunk_exists(chunk_id: str) -> bool:
    if not DB_PATH.exists():
        return False
    conn = get_db()
    try:
        return conn.execute("SELECT 1 FROM chunks WHERE chunk_id = ?", (chunk_id,)).fetchone() is not None
    except sqlite3.Error:
        return False
    finally:
        conn.close()


@mcp.tool
def store_memory(type: str, title: str, content: str, rationale: str | None = None,
                 project: str | None = None, topic_ids: list[str] | None = None) -> dict:
    """Store a new memory. Types: feedback, project, user, reference.

    Writes a markdown file under DATA_DIR/memory (the source of truth, meant to be committed)
    and indexes it so it is searchable immediately. Requires write permission. A rationale is
    required for feedback and project types.

    Deliberation-vs-outcome gate: before storing feedback/project content extracted from a
    conversation, ask "was a choice made here, or merely discussed as an option?" Options
    under consideration, leanings and unconfirmed calls are not outcomes; do not store them
    as settled fact. For decisions use store_decision(status="provisional"), which tags and
    down-weights the entry until it is corroborated.
    """
    _refuse_if_replica("memory")
    start = time.time()
    valid_types = {"feedback", "project", "user", "reference"}
    if type not in valid_types:
        return {"error": f"Invalid type '{type}'. Must be one of: {sorted(valid_types)}"}
    if type in {"feedback", "project"} and not (rationale and rationale.strip()):
        return {"error": f"Rationale is required for memory type '{type}'"}
    if not title.strip() or not content.strip():
        return {"error": "title and content must not be empty"}

    slug = _slug(title)
    filename = f"{type}_{slug}.md"
    filepath = memory_files_dir() / filename
    chunk_id = f"memory:{type}:{slug}"
    if filepath.exists() or _chunk_exists(chunk_id):
        return {"error": f"Memory already exists: {filename}"}

    body = content.strip()
    if rationale and rationale.strip() and not re.search(r"\*\*(?:Why|Rationale):?\*\*", body, re.IGNORECASE):
        body = f"{body}\n\n**Why:** {rationale.strip()}"
    # Frontmatter fields are single-line: a newline in a title could inject extra keys.
    doc = f"---\nname: {_one_line(title)}\ndescription: {_one_line(content, 100)}\ntype: {type}\n---\n\n{body}\n"
    filepath.parent.mkdir(parents=True, exist_ok=True)
    try:
        with open(filepath, "x", encoding="utf-8") as f:  # exclusive: never overwrite
            f.write(doc)
    except FileExistsError:
        return {"error": f"Memory already exists: {filename}"}

    indexed = False
    if DB_PATH.exists():
        conn = get_db()
        try:
            now = _now_iso()
            _insert_chunk(conn, {
                "chunk_id": chunk_id, "store_type": type, "source_path": str(filepath), "title": title,
                "content": body, "now": now, "project": project or DEFAULT_PROJECT,
                "topic_ids": ", ".join(topic_ids) if topic_ids else "", "weight": _store_weight(type),
            })
            # Track the file so the incremental indexer does not see it as brand-new.
            conn.execute("INSERT OR REPLACE INTO source_meta (source_path, mtime, store_type, project)"
                         " VALUES (?,?,?,?)", (str(filepath), filepath.stat().st_mtime, type,
                                               project or DEFAULT_PROJECT))
            conn.commit()
            indexed = True
        except sqlite3.Error as e:
            conn.rollback()
            app_logger.error("store_memory: file written but indexing failed: %s", e)
        finally:
            conn.close()

    committed = _git_autocommit(filepath, f"memory: {title}")
    audit_log("store_memory", f"type={type} title={title}", 1, (time.time() - start) * 1000)
    return {"stored": filename, "chunk_id": chunk_id, "indexed": indexed, "committed": committed}


@mcp.tool
def store_decision(title: str, context: str, decision: str, alternatives: str, rationale: str,
                   status: str = "decided") -> dict:
    """Append a decision to decisions/log.md using the 4-field template.

    Requires write permission. Fields: Context, Decision, Alternatives considered, Rationale.

    Deliberation-vs-outcome gate: deliberation transcripts get extracted as settled fact. Before
    calling, ask "was a choice actually made and acted on, or merely discussed?" Pass
    status="decided" ONLY for a real choice. Pass status="provisional" for options weighed,
    leanings or unconfirmed calls: these are tagged PROVISIONAL in the log, stored at reduced
    trust weight, and must not be treated as settled fact until corroborated (a later
    store_decision call or a human confirmation; there is no auto-promotion).
    """
    if status not in {"decided", "provisional"}:
        return {"error": f"Invalid status '{status}'. Must be 'decided' or 'provisional'"}
    _refuse_if_replica("decision")
    start = time.time()
    if not title.strip():
        return {"error": "title must not be empty"}
    path = decisions_log_path()
    date = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    chunk_id = f"decision:{date}:{_slug(title)}"
    if _chunk_exists(chunk_id):
        return {"error": f"A decision with this title already exists for {date}"}

    context, decision, alternatives, rationale = (
        _defang_log_text(v) for v in (context, decision, alternatives, rationale))
    status_line = ("**Status:** PROVISIONAL, deliberation-sourced, not yet corroborated\n"
                   if status == "provisional" else "")
    entry = (f"\n### {date} — {_one_line(title)}\n\n{status_line}**Context:** {context}\n"
             f"**Decision:** {decision}\n**Alternatives considered:** {alternatives}\n"
             f"**Rationale:** {rationale}\n")
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "a", encoding="utf-8") as f:
        f.write(entry)

    indexed = False
    if DB_PATH.exists():
        conn = get_db()
        try:
            base_w = _store_weight("decision", 1.5)
            _insert_chunk(conn, {
                "chunk_id": chunk_id, "store_type": "decision", "source_path": str(path), "title": title,
                "content": entry.strip(), "now": _now_iso(), "project": DEFAULT_PROJECT, "topic_ids": "",
                "weight": base_w * 0.5 if status == "provisional" else base_w,
            })
            conn.commit()
            indexed = True
        except sqlite3.Error as e:
            conn.rollback()
            app_logger.error("store_decision: log written but indexing failed: %s", e)
        finally:
            conn.close()

    committed = _git_autocommit(path, f"decision: {title}")
    audit_log("store_decision", f"title={title} status={status}", 1, (time.time() - start) * 1000)
    return {"stored": True, "date": date, "title": title, "chunk_id": chunk_id, "status": status,
            "indexed": indexed, "committed": committed}


